import argparse
import subprocess
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
_SOURCE = _ROOT / "openapi" / "reseller-api.yaml"
_OUTPUT = _ROOT / "src" / "yolla_voice" / "generated"
_TEMPLATES = _ROOT / "scripts" / "generator"


def generate_models(source: Path = _SOURCE, output: Path = _OUTPUT) -> None:
    output.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(source),
            "--input-file-type",
            "openapi",
            "--output",
            str(output / "models.py"),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.11",
            "--base-class",
            "yolla_voice._models.base.BaseModel",
            "--custom-template-dir",
            str(_TEMPLATES),
            "--additional-imports",
            "yolla_voice._models.open_enum.OpenEnum",
            "--openapi-scopes",
            "schemas",
            "paths",
            "--use-operation-id-as-name",
            "--output-datetime-class",
            "AwareDatetime",
            "--enum-field-as-literal",
            "none",
            "--snake-case-field",
            "--use-annotated",
            "--collapse-root-models",
            "--use-standard-collections",
            "--use-subclass-enum",
            "--disable-timestamp",
            "--disable-warnings",
            "--formatters",
            "builtin",
        ],
        cwd=_ROOT,
        check=True,
    )
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--fix",
            "--config",
            str(_ROOT / "pyproject.toml"),
            str(output / "models.py"),
        ],
        cwd=_ROOT,
        check=True,
    )
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--config",
            str(_ROOT / "pyproject.toml"),
            "--config",
            "format.skip-magic-trailing-comma = true",
            "--config",
            "lint.isort.split-on-trailing-comma = false",
            str(output / "models.py"),
        ],
        cwd=_ROOT,
        check=True,
    )
    (output / "__init__.py").write_text(
        "# Generated by scripts/generate_models.py; do not edit.\n"
        "from . import models as models\n\n"
        '__all__ = ["models"]\n',
        encoding="utf-8",
        newline="\n",
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate Pydantic models from the OpenAPI contract"
    )
    parser.add_argument("--source", type=Path, default=_SOURCE)
    parser.add_argument("--output", type=Path, default=_OUTPUT)
    args = parser.parse_args(argv)
    generate_models(source=args.source, output=args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
