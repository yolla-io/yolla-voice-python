import argparse
import re
import subprocess
import sys
from datetime import date
from pathlib import Path
from typing import Any

import yaml  # type: ignore[import-untyped]

_ROOT = Path(__file__).resolve().parents[1]
_PROSE_KEYS = frozenset({"description", "summary", "example", "examples", "x-mvp"})
_OPERATION_KEYS = frozenset({"get", "put", "post", "delete", "options", "head", "patch", "trace"})
_CYRILLIC_RE = re.compile(r"[\u0400-\u04ff\u0500-\u052f\u2de0-\u2dff\ua640-\ua69f]")


def strip_prose(node: Any, parent_key: str | None = None) -> Any:
    if isinstance(node, dict):
        stripped = {
            key: strip_prose(value, key)
            for key, value in node.items()
            if parent_key == "properties" or key not in _PROSE_KEYS
        }
        if parent_key == "responses":
            for response in stripped.values():
                if isinstance(response, dict):
                    response["description"] = "Response"
        elif parent_key == "paths":
            for path_item in stripped.values():
                if not isinstance(path_item, dict):
                    continue
                for method, operation in path_item.items():
                    if (
                        method in _OPERATION_KEYS
                        and isinstance(operation, dict)
                        and "operationId" in operation
                    ):
                        operation["summary"] = operation["operationId"]
        return stripped
    if isinstance(node, list):
        return [strip_prose(item, parent_key) for item in node]
    return node


def _source_commit(source: Path) -> str:
    try:
        result = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=source.parent,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    commit = result.stdout.strip()
    try:
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            cwd=source.parent,
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return commit
    return f"{commit}-dirty" if status.stdout.strip() else commit


def sync_contract(source: Path, output: Path, *, today: date | None = None) -> None:
    document = yaml.safe_load(source.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise TypeError("OpenAPI source must contain a mapping")
    info = document.get("info")
    version = info.get("version", "unknown") if isinstance(info, dict) else "unknown"
    stripped = strip_prose(document)
    header = (
        "# Generated by scripts/sync_contract.py; do not edit.\n"
        f"# Source contract version: {version}\n"
        f"# Source commit: {_source_commit(source)}\n"
        f"# Sync date: {(today or date.today()).isoformat()}\n"
    )
    body = yaml.safe_dump(
        stripped,
        allow_unicode=True,
        sort_keys=True,
        width=sys.maxsize,
    )
    rendered = header + body
    if _CYRILLIC_RE.search(rendered):
        raise ValueError("Cyrillic content remains in synchronized contract")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(rendered, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Synchronize the local OpenAPI contract snapshot")
    parser.add_argument("source", type=Path)
    args = parser.parse_args(argv)
    sync_contract(args.source, _ROOT / "openapi" / "reseller-api.yaml")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
